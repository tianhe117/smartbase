def get_pinyin(char: str) -> str:
    """Get pinyin for a character using pypinyin (most common reading)."""
    result = pinyin(char, style=Style.TONE)
    return result[0][0] if result else ""


async def lookup_words_online(char: str) -> list[str]:
    """Try to look up common words from online sources."""
    words = []

    try:
        async with httpx.AsyncClient(timeout=5.0) as client:
            # Try Baidu Dictionary API
            resp = await client.get(
                "https://dict.baidu.com/sug",
                params={"wd": char, "json": 1},
                headers={"User-Agent": "Mozilla/5.0"},
            )
            if resp.status_code == 200:
                data = resp.json()
                if data.get("data"):
                    for item in data["data"]:
                        word = item.get("word", "")
                        if word and len(word) >= 2 and char in word and word != char:
                            words.append(word)
                        if len(words) >= 3:
                            break
    except Exception:
        pass

    return words[:3]


def get_words_offline(char: str) -> list[str]:
    """Get words from built-in dictionary."""
    return COMMON_WORDS.get(char, [])


async def lookup_character(char: str) -> dict:
    """Look up pinyin and common words for a Chinese character.

    Returns dict with: char, pinyin, word_1, word_2
    """
    if len(char) != 1:
        return {"char": char, "pinyin": "", "word_1": "", "word_2": ""}

    pinyin_str = get_pinyin(char)

    # Try online lookup first
    words = await lookup_words_online(char)

    # Fallback to offline dictionary
    if len(words) < 2:
        offline = get_words_offline(char)
        for w in offline:
            if w not in words:
                words.append(w)
            if len(words) >= 2:
                break

    return {
        "char": char,
        "pinyin": pinyin_str,
        "word_1": words[0] if len(words) > 0 else "",
        "word_2": words[1] if len(words) > 1 else "",
    }
